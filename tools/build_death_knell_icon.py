"""Builds src/coop/death_knell_art.inc: the Death Knell's icon (assets/DeathKnell.png, 80 x 90) for each mip level of
the cell it is drawn from.

The game draws a goods icon from the sprite EquIcon_<iconId> of menu.drb's "Icon" dialog. The Death Knell uses icon
2159: its sprite reads the 80 x 90 cell (247, 185)-(327, 275) of the atlas "Icon21" (menu/menu_4.tpf, 1024 x 512 DXT5),
a cell no item uses and the game leaves empty (2159-2167 are all blank). At run time (deathknell.cpp) the cell's DXT5
blocks are read, this art is laid over them and the blocks are written back, level by level. Each level's patch here
is the art scaled to that level, on the level's 4 x 4 blocks that cover the cell, transparent elsewhere; no pixel of
the game's own is in it.

usage: build_death_knell_icon.py      (then rebuild)
Needs numpy and Pillow.
"""
# SPDX-License-Identifier: GPL-3.0-or-later
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'assets', 'DeathKnell.png')
OUT = os.path.join(ROOT, 'src', 'coop', 'death_knell_art.inc')
CELL = (247, 185, 327, 275)  # EquIcon_2159 in Icon21, level 0
ATLAS = (1024, 512)
LEVELS = 5


def main():
    art = np.asarray(Image.open(ART).convert('RGBA')).astype(np.float64) / 255.0
    assert art.shape[:2] == (CELL[3] - CELL[1], CELL[2] - CELL[0]), art.shape
    out = []
    blobs = []
    for level in range(LEVELS):
        f = 1 << level
        x0 = (CELL[0] // f) // 4 * 4
        y0 = (CELL[1] // f) // 4 * 4
        x1 = min(-(-(-(-CELL[2] // f)) // 4) * 4, ATLAS[0] // f)
        y1 = min(-(-(-(-CELL[3] // f)) // 4) * 4, ATLAS[1] // f)
        # The art at level 0 on the level-0 area of these blocks, then scaled down f times (premultiplied box filter).
        big = np.zeros(((y1 - y0) * f, (x1 - x0) * f, 4))
        ox, oy = CELL[0] - x0 * f, CELL[1] - y0 * f
        big[oy:oy + art.shape[0], ox:ox + art.shape[1]] = art
        pm = big.copy()
        pm[..., :3] *= pm[..., 3:4]
        small = pm.reshape(y1 - y0, f, x1 - x0, f, 4).mean(axis=(1, 3))
        a = small[..., 3:4]
        rgb = np.where(a > 1e-6, small[..., :3] / np.maximum(a, 1e-6), 0)
        px = np.concatenate([rgb, a], -1)
        bgra = (np.clip(px[..., [2, 1, 0, 3]], 0, 1) * 255 + 0.5).astype(np.uint8)
        out.append((level, x0, y0, x1, y1, len(b''.join(blobs))))
        blobs.append(bgra.tobytes())
    data = b''.join(blobs)
    lines = ['// Generated by tools/build_death_knell_icon.py (assets/DeathKnell.png). Do not edit.',
             '// Per level: {level, left, top, right, bottom, offset into kKnellArt}; the art is BGRA (D3DFMT_A8R8G8B8),',
             '// straight alpha, row by row across the rectangle.',
             'struct KnellLevel {',
             '    int level, left, top, right, bottom, offset;',
             '};',
             'const KnellLevel kKnellLevels[%d] = {' % LEVELS]
    for lv in out:
        lines.append('    {%d, %d, %d, %d, %d, %d},' % lv)
    lines.append('};')
    lines.append('const unsigned char kKnellArt[%d] = {' % len(data))
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',')
    lines.append('};')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(data), 'bytes;', out)


if __name__ == '__main__':
    main()
