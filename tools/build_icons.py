"""Builds src/coop/icon_art.inc: Prepare to Co-op's own item icons (80 x 90 each) for each mip level of the cell they
are drawn from.

The game draws a goods icon from the sprite EquIcon_<iconId> of menu.drb's "Icon" dialog. The atlas "Icon21"
(menu/menu_4.tpf, 1024 x 512 DXT5) has cells no item uses, which the game leaves empty (2159-2167 are all blank):
  - the Death Knell, icon 2159: the cell (247, 185)-(327, 275), assets/DeathKnell.png (tools/paint_death_knell.py);
  - the Vigil Soapstone, icon 2160: the cell (329, 185)-(409, 275), assets/VigilSoapstone.png
    (tools/paint_vigil_soapstone.py, from the game's White Sign Soapstone).
At run time (knell.cpp) each cell's DXT5 blocks are read, the art is laid over them and the blocks are written back,
level by level. Each level's patch here is the art scaled to that level, on the level's 4 x 4 blocks that cover the
cell, transparent elsewhere (two cells can share a block at the smaller levels: each is laid over what is there).

usage: build_icons.py      (then rebuild)
Needs numpy and Pillow.
"""
# SPDX-License-Identifier: GPL-3.0-or-later
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'coop', 'icon_art.inc')
ATLAS = (1024, 512)
LEVELS = 5
# (name, art, cell in Icon21 at level 0, symbol)
ICONS = [
    ('Death Knell', 'DeathKnell.png', (247, 185, 327, 275), 'DeathKnell'),
    ('Vigil Soapstone', 'VigilSoapstone.png', (329, 185, 409, 275), 'VigilSoapstone'),
]


def patches(art_path, cell):
    art = np.asarray(Image.open(art_path).convert('RGBA')).astype(np.float64) / 255.0
    assert art.shape[:2] == (cell[3] - cell[1], cell[2] - cell[0]), art.shape
    out = []
    blobs = []
    for level in range(LEVELS):
        f = 1 << level
        x0 = (cell[0] // f) // 4 * 4
        y0 = (cell[1] // f) // 4 * 4
        x1 = min(-(-(-(-cell[2] // f)) // 4) * 4, ATLAS[0] // f)
        y1 = min(-(-(-(-cell[3] // f)) // 4) * 4, ATLAS[1] // f)
        # The art at level 0 on the level-0 area of these blocks, then scaled down f times (premultiplied box filter).
        big = np.zeros(((y1 - y0) * f, (x1 - x0) * f, 4))
        ox, oy = cell[0] - x0 * f, cell[1] - y0 * f
        big[oy:oy + art.shape[0], ox:ox + art.shape[1]] = art
        pm = big.copy()
        pm[..., :3] *= pm[..., 3:4]
        small = pm.reshape(y1 - y0, f, x1 - x0, f, 4).mean(axis=(1, 3))
        a = small[..., 3:4]
        rgb = np.where(a > 1e-6, small[..., :3] / np.maximum(a, 1e-6), 0)
        px = np.concatenate([rgb, a], -1)
        bgra = (np.clip(px[..., [2, 1, 0, 3]], 0, 1) * 255 + 0.5).astype(np.uint8)
        out.append((level, x0, y0, x1, y1, len(b''.join(blobs))))
        blobs.append(bgra.tobytes())
    return out, b''.join(blobs)


def main():
    lines = ['// Generated by tools/build_icons.py (%s). Do not edit.' % ', '.join('assets/' + i[1] for i in ICONS),
             '// Per level: {level, left, top, right, bottom, offset into the art}; the art is BGRA (D3DFMT_A8R8G8B8),',
             '// straight alpha, row by row across the rectangle.',
             'struct IconLevel {',
             '    int level, left, top, right, bottom, offset;',
             '};',
             'struct IconArt {',
             '    const char* name;',
             '    const IconLevel* levels;',
             '    int count;',
             '    const unsigned char* art;',
             '};']
    for name, png, cell, sym in ICONS:
        levels, data = patches(os.path.join(ROOT, 'assets', png), cell)
        lines.append('const IconLevel k%sLevels[%d] = {' % (sym, LEVELS))
        for lv in levels:
            lines.append('    {%d, %d, %d, %d, %d, %d},' % lv)
        lines.append('};')
        lines.append('const unsigned char k%sArt[%d] = {' % (sym, len(data)))
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',')
        lines.append('};')
        print(name, len(data), 'bytes;', levels)
    lines.append('const IconArt kIcons[%d] = {' % len(ICONS))
    for name, _png, _cell, sym in ICONS:
        lines.append('    {"%s", k%sLevels, %d, k%sArt},' % (name, sym, LEVELS, sym))
    lines.append('};')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
