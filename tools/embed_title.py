"""Writes src/title_art.inc from assets/PrepareToCoop-Title.png (the title logo the mod uses
while Prepare to Co-op is on). Run it again after changing the PNG, then rebuild."""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'assets', 'PrepareToCoop-Title.png')
dst = os.path.join(root, 'src', 'title_art.inc')
data = open(src, 'rb').read()
assert data[:8] == b'\x89PNG\r\n\x1a\n', 'not a PNG'
lines = ['// Generated by tools/embed_title.py from assets/PrepareToCoop-Title.png. Do not edit.',
         'const unsigned char kTitleArt[%d] = {' % len(data)]
for i in range(0, len(data), 24):
    lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',')
lines.append('};')
open(dst, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote %s (%d bytes of PNG)' % (dst, len(data)))
